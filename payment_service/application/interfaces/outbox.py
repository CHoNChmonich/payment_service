"""Порт outbox — событий платежей, ожидающих публикации."""

from abc import ABC, abstractmethod
from collections.abc import Sequence
from uuid import UUID

from payment_service.application import dtos


class OutboxRepo(ABC):
    """Исходящие события платежей, ожидающие публикации (transactional outbox).

    Сервис добавляет событие в той же транзакции, что и платёж: событие существует тогда и
    только тогда, когда зафиксирован факт. Публикация — не менее одного раза: событие
    удаляется после подтверждения брокера, сбой между подтверждением и фиксацией удаления
    приводит к повторной публикации. Порядок событий не гарантируется (платежи независимы),
    поэтому публиковать могут несколько экземпляров relay одновременно: выбранная одним
    экземпляром пачка невидима для других до конца его транзакции.
    """

    @abstractmethod
    async def add(self, event: dtos.PaymentCreated) -> None:
        """Добавляет событие к транзакции.

        Args:
            event: Событие сценария.
        """

    @abstractmethod
    async def fetch_batch(self, limit: int) -> list[dtos.PaymentCreated]:
        """Выбирает и закрепляет за текущей транзакцией пачку неопубликованных событий.

        События, закреплённые другой транзакцией, пропускаются; закрепление снимается с
        концом транзакции.

        Args:
            limit: Наибольшее число событий в пачке.

        Returns:
            События в порядке добавления; пустой список, если публиковать нечего.
        """

    @abstractmethod
    async def delete(self, event_ids: Sequence[UUID]) -> None:
        """Удаляет опубликованные события.

        Args:
            event_ids: Идентификаторы событий, доставку которых подтвердил брокер.
        """
