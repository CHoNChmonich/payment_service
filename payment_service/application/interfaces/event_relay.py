"""Входящий порт сценария доставки событий из outbox."""

from abc import ABC, abstractmethod

from payment_service.application import dtos


class EventRelay(ABC):
    """Доставка накопленных событий платежей — входящий порт.

    Вызывает его входящий адаптер по таймеру; контракт описан здесь, реализация описывает
    только особенности исполнения.
    """

    @abstractmethod
    async def relay(self) -> dtos.RelayResult:
        """Публикует по очередной пачке событий каждого типа и удаляет опубликованные.

        Быстрый временный отказ доставки одного типа не задерживает остальные: их пачки
        публикуются и удаляются, итог называет число опубликованных и типы со сбоем —
        вызывающий сразу идёт за следующими. События типа со сбоем остаются в outbox. Сбой
        поднимается, только когда не опубликовано ничего. Дорожки проходятся по очереди:
        отказ, пришедший по дедлайну публикации, на этот дедлайн задерживает и следующую.

        Returns:
            Число опубликованных событий (``0`` — публиковать нечего) и типы со сбоем.

        Raises:
            BrokerUnavailable: Брокер не подтвердил доставку, и ни одна пачка не опубликована.
            StorageUnavailable: Временный сбой хранилища, и ни одна пачка не опубликована.
        """
