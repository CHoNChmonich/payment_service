"""Входящий порт сценария доставки событий из outbox."""

from abc import ABC, abstractmethod


class EventRelay(ABC):
    """Доставка накопленных событий платежей — входящий порт.

    Вызывает его входящий адаптер по таймеру; контракт описан здесь, реализация описывает
    только особенности исполнения.
    """

    @abstractmethod
    async def relay(self) -> int:
        """Публикует очередную пачку событий outbox и удаляет опубликованные.

        Returns:
            Сколько событий опубликовано; ``0`` — публиковать нечего.

        Raises:
            BrokerUnavailable: Брокер не подтвердил доставку; события остаются в outbox.
            StorageUnavailable: Временный сбой хранилища.
        """
