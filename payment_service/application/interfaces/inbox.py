"""Порт inbox — обработанных входящих сообщений."""

from abc import ABC, abstractmethod
from uuid import UUID


class InboxRepo(ABC):
    """Идентификаторы обработанных входящих сообщений — идемпотентность их обработки.

    Сообщение регистрируется в той же транзакции, что и его эффект: при откате регистрация
    исчезает вместе с эффектом, и повторная доставка обработает сообщение заново. Параллельная
    регистрация того же идентификатора ждёт исхода первой транзакции.
    """

    @abstractmethod
    async def register(self, message_id: UUID, fingerprint: str) -> bool:
        """Регистрирует сообщение в текущей транзакции.

        Args:
            message_id: Ключ идемпотентности сообщения, присвоенный источником.
            fingerprint: Отпечаток значимого содержимого сообщения.

        Returns:
            ``True`` — сообщение регистрируется впервые; ``False`` — уже обработано с тем же
            отпечатком (повторная доставка).

        Raises:
            MessageConflict: Сообщение уже обработано с другим отпечатком.
        """
